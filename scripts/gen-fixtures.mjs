#!/usr/bin/env node
// Embeds fixtures/*.json into tests/Fixtures.elm so the Elm decoder tests
// exercise the exact documents the JS serializer tests produce.
// CI regenerates and fails if the committed file drifts.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const fixtures = [
  ['fullJson', 'fixtures/full.json'],
  ['emptyJson', 'fixtures/empty.json'],
]

const bodies = fixtures.map(([name, rel]) => {
  const json = JSON.stringify(JSON.parse(readFileSync(path.join(root, rel), 'utf8')))
  if (json.includes('"""') || json.includes('\\')) {
    throw new Error(`${rel} contains characters that need escaping in an Elm string`)
  }
  return `{-| \`${rel}\`, minified.
-}
${name} : String
${name} =
    """${json}"""
`
})

const out = `module Fixtures exposing (${fixtures.map(([n]) => n).join(', ')})

{-| GENERATED by scripts/gen-fixtures.mjs from fixtures/*.json. Do not edit.

@docs ${fixtures.map(([n]) => n).join(', ')}

-}


${bodies.join('\n\n')}`

writeFileSync(path.join(root, 'tests/Fixtures.elm'), out)
console.log('wrote tests/Fixtures.elm')
